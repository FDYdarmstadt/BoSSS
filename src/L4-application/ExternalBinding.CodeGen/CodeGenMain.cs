using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Security.Cryptography;
using System.Text;
using ilPSP;
using ilPSP.Connectors;

namespace BoSSS.Application.ExternalBinding.CodeGen {
    /// <summary>Generates matching C++ wrappers and blittable .NET hosting entry points.</summary>
    static class CodeGenMain {
        static readonly Type Proxy = typeof(IForeignLanguageProxy);
        const string Banner = "// Generated by ExternalBinding.CodeGen. Do not edit.\n";

        static Type[] ExportTypes() => BoSSS.Solution.Application.GetAllAssemblies(typeof(FixedOperators))
            .Concat(BoSSS.Solution.Application.GetAllAssemblies(typeof(CodeGenMain))).Distinct()
            .Where(a => a.GetName().Name.StartsWith("BoSSS") || a.GetName().Name.StartsWith("ilPSP") || a.GetName().Name.StartsWith("MPI.Wrappers"))
            .SelectMany(a => a.GetTypes()).Where(t => t.IsClass && Proxy.IsAssignableFrom(t))
            .OrderBy(t => t.FullName, StringComparer.Ordinal).ToArray();

        static bool Exported(MemberInfo m) => m.IsDefined(typeof(CodeGenExportAttribute), false);
        static string Managed(Type t) {
            if (Proxy.IsAssignableFrom(t)) return "global::" + t.FullName;
            if (t == typeof(void)) return "void";
            if (t == typeof(int)) return "int";
            if (t == typeof(double)) return "double";
            if (t == typeof(IntPtr)) return "nint";
            if (t.IsPointer) return Managed(t.GetElementType()) + "*";
            if (t == typeof(int).MakeByRefType()) return "int*";
            throw new NotSupportedException("Unsupported export type: " + t);
        }
        static string AbiManaged(Type t) => Proxy.IsAssignableFrom(t) ? "nint" : Managed(t);
        static string Cpp(Type t, bool abi = false) {
            if (Proxy.IsAssignableFrom(t)) return abi ? "void*" : t.FullName.Replace(".", "::") + "*";
            if (t == typeof(IntPtr)) return "void*";
            return Managed(t);
        }
        static string Id(Type t, MethodBase m, int ordinal) =>
            t.FullName.Replace('.', '_') + "_" + (m is ConstructorInfo ? "ctor" : m.Name) + "_" + ordinal;
        static string Template(string name) {
            using (var stream = typeof(CodeGenMain).Assembly.GetManifestResourceStream(
                "BoSSS.Application.ExternalBinding.CodeGen." + name)) {
                if (stream == null) throw new FileNotFoundException("Missing generator template", name);
                using (var reader = new StreamReader(stream)) return reader.ReadToEnd();
            }
        }
        static void Write(string dir, string file, string content) => File.WriteAllText(Path.Combine(dir, file), (file.EndsWith(".sh", StringComparison.Ordinal) ? content : Banner + content));

        public static void Main(string[] args) {
            if (args.Length < 1 || args.Length > 2)
                throw new ArgumentException("usage: ExternalBinding.CodeGen <C++ output directory> [C# output directory]");
            Generate(args[0], args.Length == 2 ? args[1] : args[0]);
        }

        internal static void Generate(string cppDirectory, string managedDirectory) {
            Directory.CreateDirectory(cppDirectory);
            Directory.CreateDirectory(managedDirectory);
            var types = ExportTypes();
            if (types.Select(t => t.Name).Distinct().Count() != types.Length)
                throw new NotSupportedException("Exported types must have distinct simple names.");
            // Construct all outputs before writing; never delete unrelated files in the destination.
            var files = new Dictionary<string, string>();
            var cs = new StringBuilder("namespace BoSSS.Application.ExternalBinding {\npublic static unsafe partial class NativeExports {\n");
            var includes = new StringBuilder("#pragma once\n#include \"Globals.h\"\n#include \"Prototypes.h\"\n");
            var prototypes = new StringBuilder("#pragma once\n");
            foreach (var t in types) {
                if (t.IsAbstract || t.IsGenericType) throw new NotSupportedException("Unsupported export class: " + t);
                Console.WriteLine("Exporting " + t.FullName);
                string open = string.Join(" ", t.Namespace.Split('.').Select(n => "namespace " + n + " {"));
                string close = new string('}', t.Namespace.Split('.').Length);
                prototypes.AppendLine(open + " class " + t.Name + "; " + close);
                includes.AppendLine("#include \"" + t.Name + ".h\"");
                var header = new StringBuilder("#pragma once\n#include \"Globals.h\"\n#include \"Prototypes.h\"\n" + open + "\nclass " + t.Name + " : public BoSSS::NativeObject {\npublic:\n");
                header.AppendLine("static " + t.Name + "* _FromHandle(void* handle);");
                var cpp = new StringBuilder("#include \"BoSSScpp.h\"\n" + open + "\n");
                cpp.AppendLine(t.Name + "* " + t.Name + "::_FromHandle(void* handle) {\n    if (!handle) return nullptr;\n    try {\n        void* foreign = BoSSS::Globals::Foreign(handle);\n        if (foreign) {\n            BoSSS::Globals::Release(handle, false);\n            return static_cast<" + t.Name + "*>(foreign);\n        }\n        return new " + t.Name + "(handle, Adopt{});\n    } catch (...) { BoSSS::Globals::Release(handle, false); throw; }\n}");
                var interfaceMethods = t.GetInterfaceMap(Proxy).TargetMethods;
                var members = t.GetConstructors().Where(Exported).Cast<MethodBase>()
                    .Concat(t.GetMethods(BindingFlags.Public | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly)
                        .Where(m => Exported(m) || interfaceMethods.Contains(m)))
                    .OrderBy(m => m.ToString(), StringComparer.Ordinal).ToArray();
                for (int i = 0; i < members.Length; i++) Emit(t, members[i], Id(t, members[i], i), cs, header, cpp);
                header.AppendLine("private:\nstruct Adopt {};\n" + t.Name + "(void* handle, Adopt) { _Adopt(handle, this); }\n};\n" + close);
                cpp.AppendLine(close);
                files[t.Name + ".h"] = header.ToString();
                files[t.Name + ".cpp"] = cpp.ToString();
            }
            string fingerprint = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(cs.ToString()))).Substring(0, 16);
            cs.AppendLine("[global::System.Runtime.InteropServices.UnmanagedCallersOnly(CallConvs = new[] { typeof(global::System.Runtime.CompilerServices.CallConvCdecl) })]");
            cs.AppendLine("public static ulong AbiFingerprint() => 0x" + fingerprint + "UL;");
            cs.AppendLine("}\n}");
            files["BoSSScpp.h"] = includes.ToString();
            files["Prototypes.h"] = prototypes.ToString();
            files["Globals.h"] = Template("NativeGlobals.h.txt");
            files["Globals.cpp"] = Template("NativeGlobals.cpp.txt").Replace("@ABI@", fingerprint);
            files["ExtBindingTest.cpp"] = Template("ExtBindingTest_cpp.txt");
            files["compile.sh"] = Template("compile_sh.txt");
            foreach (var file in files) Write(cppDirectory, file.Key, file.Value);
            Write(managedDirectory, "NativeExports.g.cs", cs.ToString());
        }

        static void Emit(Type type, MethodBase method, string id, StringBuilder cs, StringBuilder header, StringBuilder cpp) {
            if (method.IsGenericMethod || method.IsAbstract) throw new NotSupportedException("Unsupported export: " + method);
            bool ctor = method is ConstructorInfo;
            Type ret = ctor ? type : ((MethodInfo)method).ReturnType;
            bool result = ret != typeof(void);
            bool self = !ctor && !method.IsStatic;
            var ps = method.GetParameters();
            var abiCs = new List<string>();
            var abiCpp = new List<string>();
            var nativeArgs = new List<string>();
            if (self) { abiCs.Add("nint self"); abiCpp.Add("void*"); nativeArgs.Add("_ManagedHandle()"); }
            for (int i = 0; i < ps.Length; i++) {
                Type p = ps[i].ParameterType;
                abiCs.Add(AbiManaged(p) + " a" + i);
                abiCpp.Add(Cpp(p, true));
                nativeArgs.Add(Proxy.IsAssignableFrom(p) ? "(a" + i + " ? a" + i + "->_ManagedHandle() : nullptr)" : "a" + i);
            }
            if (result) { abiCs.Add(AbiManaged(ret) + "* result"); abiCpp.Add(Cpp(ret, true) + "*"); nativeArgs.Add("&result"); }
            cs.AppendLine("[global::System.Runtime.InteropServices.UnmanagedCallersOnly(CallConvs = new[] { typeof(global::System.Runtime.CompilerServices.CallConvCdecl) })]");
            cs.AppendLine("public static int " + id + "(" + string.Join(", ", abiCs) + ") {\n    try {");
            if (result) cs.AppendLine("        if (result == null) throw new global::System.ArgumentNullException(nameof(result));\n        *result = default;");
            string target = ctor ? "new " + Managed(type) : (self ? "NativeExportRuntime.Target<" + Managed(type) + ">(self)." + method.Name : Managed(type) + "." + method.Name);
            string args = string.Join(", ", ps.Select((p, i) => Proxy.IsAssignableFrom(p.ParameterType)
                ? "NativeExportRuntime.Target<" + Managed(p.ParameterType) + ">(a" + i + ", allowNull: true)"
                : (p.ParameterType.IsByRef ? (p.IsOut ? "out " : "ref ") + "*a" + i : "a" + i)));
            string call = target + "(" + args + ")";
            cs.AppendLine(result ? "        *result = " + (Proxy.IsAssignableFrom(ret) ? "NativeExportRuntime.Root(" + call + ")" : call) + ";" : "        " + call + ";");
            cs.AppendLine("        return 0;\n    } catch (global::System.Exception error) { return NativeExportRuntime.Fail(error); }\n}");

            string declParams = string.Join(", ", ps.Select((p, i) => Cpp(p.ParameterType) + " a" + i));
            string name = ctor ? type.Name : method.Name;
            header.AppendLine((!ctor && method.IsStatic ? "static " : "") + (ctor ? "" : Cpp(ret) + " ") + name + "(" + declParams + ");");
            cpp.AppendLine((ctor ? "" : Cpp(ret) + " ") + type.Name + "::" + name + "(" + declParams + ") {");
            cpp.AppendLine("    BoSSS::ManagedCallScope managedCall;\n    typedef int (*Fn)(" + string.Join(", ", abiCpp) + ");\n    static Fn fn = reinterpret_cast<Fn>(BoSSS::Globals::Resolve(\"" + id + "\"));");
            if (result) cpp.AppendLine("    " + Cpp(ret, true) + " result{};");
            cpp.AppendLine("    BoSSS::Globals::Check(fn(" + string.Join(", ", nativeArgs) + "), \"" + type.Name + "." + name + "\");");
            if (ctor) cpp.AppendLine("    try { _Adopt(result, this); } catch (...) { BoSSS::Globals::Release(result, false); throw; }");
            else if (result) cpp.AppendLine("    return " + (Proxy.IsAssignableFrom(ret) ? ret.FullName.Replace(".", "::") + "::_FromHandle(result)" : "result") + ";");
            cpp.AppendLine("}");
        }
    }
}
