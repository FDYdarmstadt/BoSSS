using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;

namespace MltdimAryMultiply_CodeGen {

    /// <summary>
    /// Generates the register-blocked AVX2 micro-kernels for the GETT-style Multiply path
    /// (<c>MultidimensionalArray_CodeGenMultiplySimd.cs</c>; driver: <c>MultidimensionalArray_MultiplyGett.cs</c>).
    /// </summary>
    /// <remarks>
    /// Operands are normalized to X (varies along the vector axis v, i.e. the unit-stride axis of T)
    /// and Y (the other operand); A and B are swapped if necessary (IEEE multiplication is commutative,
    /// so this does not change any result bit).
    ///
    /// Kernel <c>Gett_{MR}x{NV}_{XM}{YM}{R}_S{NS}</c> computes MR x (4*NV) entries of T, in <c>nrb</c>
    /// consecutive blocks of MR rows (row axis r, pointer strides tr, xr, yr); columns along v (T stride 1),
    /// the last of the NV column vectors is masked (<c>mask</c>), i.e. no scalar tails.
    ///  - XM: X along v: U = unit stride (vector load), G = stride gx (gather)
    ///  - YM: Y along v: B = constant (broadcast), U = unit stride, G = stride gy (gather)
    ///  - R (only YM = B): 1 = X constant along r, X is loaded once per summation step and re-used for
    ///    all MR rows (outer-product kernel); 0 = X loaded per row
    ///  - NS: number of summation loops (0, 1, 2); k0 outer, k1 inner.
    /// The arithmetic per entry of T is the same as in the generated reference kernels
    /// (Multiply_Sum*), hence results are bitwise identical:
    ///  - NS &gt; 0: acc = 0; acc += x*y (summation order k0, k1); T = acc*alpha + T*beta
    ///  - NS = 0: T = (x*y)*alpha + T*beta
    /// (no fused multiply-add, no reordering of the summation).
    /// </remarks>
    static class SimdKernelGen {

        static readonly int[] MRS = { 1, 2, 3, 4 };
        static readonly int[] NVS = { 1, 2, 3 };
        static readonly (char X, char Y, int R)[] PATTERNS = {
            ('U', 'B', 1), ('U', 'B', 0), ('G', 'B', 1), ('G', 'B', 0),
            ('U', 'U', 0), ('U', 'G', 0), ('G', 'G', 0) };
        // (G, U) does not occur: the driver chooses a unit-stride operand as X whenever there is one.
        static readonly int[] NSS = { 0, 1, 2 };

        static string KName(int MR, int NV, (char X, char Y, int R) p, int NS) => $"Gett_{MR}x{NV}_{p.X}{p.Y}{p.R}_S{NS}";

        public static void Generate(TextWriter Out) {
            Out.WriteLine("// <auto-generated>");
            Out.WriteLine("// Generated by MltdimAryMultiply_CodeGen (--simd), see SimdKernelGen.cs; do not edit by hand.");
            Out.WriteLine("// </auto-generated>");
            Out.WriteLine("using System.Runtime.CompilerServices;");
            Out.WriteLine("using System.Runtime.Intrinsics;");
            Out.WriteLine("using System.Runtime.Intrinsics.X86;");
            Out.WriteLine("namespace ilPSP {");
            Out.WriteLine("    partial class MultidimensionalArray {");
            Out.WriteLine("        // pattern index: " + string.Join(", ", PATTERNS.Select((p, i) => $"{i}={p.X}{p.Y}{p.R}")));
            Out.WriteLine($"        const int GETT_NPAT = {PATTERNS.Length};");

            var order = new List<(int MR, int NV, int ip, int NS)>();
            foreach(int MR in MRS)
                foreach(int NV in NVS)
                    for(int ip = 0; ip < PATTERNS.Length; ip++)
                        foreach(int NS in NSS)
                            order.Add((MR, NV, ip, NS));

            foreach(var o in order)
                Kernel(Out, o.MR, o.NV, PATTERNS[o.ip], o.NS);

            string sig = "delegate*<double*, double*, double*, int, int, int, int, int, int, int, int, int, int, int, double, double, Vector256<double>, int, void>";
            Out.WriteLine("        // index = (((MR-1)*3 + (NV-1))*GETT_NPAT + pattern)*3 + NS");
            Out.WriteLine($"        unsafe static readonly {sig}[] s_GettKernels = new {sig}[] {{");
            foreach(var o in order)
                Out.WriteLine($"            &{KName(o.MR, o.NV, PATTERNS[o.ip], o.NS)},");
            Out.WriteLine("        };");
            Out.WriteLine("    }");
            Out.WriteLine("}");
        }

        static void Kernel(TextWriter Out, int MR, int NV, (char X, char Y, int R) pat, int NS) {
            char XM = pat.X, YM = pat.Y;
            int R = pat.R;
            string name = KName(MR, NV, pat, NS);
            var L = new List<string>();
            void w(string s) => L.Add(s);
            string[,] acc = new string[MR, NV];
            for(int r = 0; r < MR; r++)
                for(int c = 0; c < NV; c++)
                    acc[r, c] = $"c{r}_{c}";

            w("        [MethodImpl(MethodImplOptions.AggressiveOptimization)]");
            w($"        unsafe static void {name}(double* t, double* x, double* y, int tr, int xr, int yr, int gx, int gy,");
            w("            int K0, int sx0, int sy0, int K1, int sx1, int sy1, double alpha, double beta, Vector256<double> mask, int nrb) {");
            if(XM == 'G')
                w("            var ix = Vector128.Create(0, gx, 2 * gx, 3 * gx);");
            if(YM == 'G')
                w("            var iy = Vector128.Create(0, gy, 2 * gy, 3 * gy);");
            w("            var va = Vector256.Create(alpha); var vb = Vector256.Create(beta);");
            w($"            for(; nrb > 0; nrb--, t += {MR} * tr, x += {MR} * xr, y += {MR} * yr) {{");

            string VLoad(string ptr, int c, char mode, string g, string iname) {
                bool last = c == NV - 1;
                if(mode == 'U') {
                    string off = $"{ptr} + {4 * c}";
                    return last ? $"Avx.MaskLoad({off}, mask)" : $"Avx.LoadVector256({off})";
                }
                if(mode == 'G') {
                    string off = $"{ptr} + {4 * c} * {g}";
                    return last ? $"Avx2.GatherMaskVector256(Vector256<double>.Zero, {off}, {iname}, mask, 8)"
                                : $"Avx2.GatherVector256({off}, {iname}, 8)";
                }
                throw new ArgumentException();
            }

            string Update(string a, string xv, string yv, string ind) {
                if(NS == 0)
                    return $"{ind}{a} = Avx.Multiply({xv}, {yv});";
                return $"{ind}{a} = Avx.Add({a}, Avx.Multiply({xv}, {yv}));";
            }

            List<string> Body(string px, string py, string ind) {
                var o = new List<string>();
                if(YM == 'B' && R == 1) {
                    for(int c = 0; c < NV; c++)
                        o.Add($"{ind}var xv{c} = {VLoad(px, c, XM, "gx", "ix")};");
                    for(int r = 0; r < MR; r++) {
                        string yp = r > 0 ? $"{py} + {r}*yr" : py;
                        o.Add($"{ind}{{ var yb = Vector256.Create(*({yp}));");
                        for(int c = 0; c < NV; c++)
                            o.Add(Update(acc[r, c], $"xv{c}", "yb", ind + "  "));
                        o.Add($"{ind}}}");
                    }
                } else {
                    for(int r = 0; r < MR; r++) {
                        string xp = r > 0 ? $"{px} + {r}*xr" : px;
                        string yp = r > 0 ? $"{py} + {r}*yr" : py;
                        if(YM == 'B') {
                            o.Add($"{ind}{{ var yb = Vector256.Create(*({yp}));");
                            for(int c = 0; c < NV; c++)
                                o.Add(Update(acc[r, c], VLoad(xp, c, XM, "gx", "ix"), "yb", ind + "  "));
                            o.Add($"{ind}}}");
                        } else {
                            for(int c = 0; c < NV; c++)
                                o.Add(Update(acc[r, c], VLoad(xp, c, XM, "gx", "ix"), VLoad(yp, c, YM, "gy", "iy"), ind));
                        }
                    }
                }
                return o;
            }

            for(int r = 0; r < MR; r++)
                for(int c = 0; c < NV; c++)
                    w($"            Vector256<double> {acc[r, c]} = Vector256<double>.Zero;");
            if(NS == 0) {
                L.AddRange(Body("x", "y", "            "));
            } else if(NS == 1) {
                w("            double* px = x, py = y;");
                w("            for(int k0 = K0; k0 > 0; k0--) {");
                L.AddRange(Body("px", "py", "                "));
                w("                px += sx0; py += sy0;");
                w("            }");
            } else {
                w("            for(int k0 = 0; k0 < K0; k0++) {");
                w("                double* px = x + k0 * sx0, py = y + k0 * sy0;");
                w("                for(int k1 = K1; k1 > 0; k1--) {");
                L.AddRange(Body("px", "py", "                    "));
                w("                    px += sx1; py += sy1;");
                w("                }");
                w("            }");
            }
            for(int r = 0; r < MR; r++) {
                string tp = r > 0 ? $"t + {r}*tr" : "t";
                for(int c = 0; c < NV; c++) {
                    if(c == NV - 1)
                        w($"            {{ var tv = Avx.MaskLoad({tp} + {4 * c}, mask); Avx.MaskStore({tp} + {4 * c}, mask, Avx.Add(Avx.Multiply({acc[r, c]}, va), Avx.Multiply(tv, vb))); }}");
                    else
                        w($"            {{ var tv = Avx.LoadVector256({tp} + {4 * c}); Avx.Store({tp} + {4 * c}, Avx.Add(Avx.Multiply({acc[r, c]}, va), Avx.Multiply(tv, vb))); }}");
                }
            }
            w("            }");
            w("        }");
            foreach(var s in L)
                Out.WriteLine(s);
        }
    }
}
