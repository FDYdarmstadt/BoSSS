using System.Runtime.CompilerServices;
using System.Runtime.Intrinsics;
using System.Runtime.Intrinsics.X86;

namespace ilPSP {
    public partial class MultidimensionalArray {

        // ==========================================================================================
        // Blocked AVX2 ("GETT-style") Multiply path (PLAN-4 Phase F,
        // .agent/kummer/tensorproductoptimization/).
        // ------------------------------------------------------------------------------------------
        // Works on the same raw loop description as the generated dispatchers (running loops: lengths
        // and cycles of T, A, B; summation loops: lengths and cycles of A, B):
        //  - vector axis v: the running loop along which T has unit stride; vectorized over 4 doubles,
        //    tails by masked loads/stores; if T has no unit-stride loop (strided views), the T block of
        //    vector and row axis is "staged", i.e. copied into a contiguous stack buffer, computed there by
        //    the same kernels, and copied back (no change of the arithmetic);
        //  - row axis r: a second running loop, register-blocked in blocks of up to 4 rows; preferably
        //    one along which the vectorized operand is constant (outer-product kernel, i.e. its vector
        //    loads are re-used for all rows of the block);
        //  - all other running loops: outer loops; an index-transformed loop is an outer (batch) loop
        //    with indirection.
        // The micro-kernels (MultidimensionalArray_CodeGenMultiplySimd.cs) are generated by
        // MltdimAryMultiply_CodeGen --simd. They keep the per-entry arithmetic and summation order of the
        // generated reference kernels (no FMA), hence the results are bitwise identical to those.
        // Only used if the destination does not share storage with an operand (as the BLAS paths);
        // selection: BLAS paths -> this path (if applicable and profitable) -> generated kernels.
        // ==========================================================================================

        const int GETT_MAXD = 8;

        /// <summary> max. size (doubles) of the stack buffer for a staged T block </summary>
        const int GETT_STAGE_MAX = 2048;

        /// <summary>
        /// if true, a unit-stride T loop of length &lt;= 3 (e.g. the spatial direction) may be replaced by a
        /// longer, staged vector axis (internal switch for measurements, see PLAN-4/RESULTS-4.md)
        /// </summary>
        internal static bool s_GettStageShortVector = false;

        /// <summary> execution plan of the blocked SIMD path for one call </summary>
        unsafe struct GettPlan {
            public int lenV, lenR;
            public bool swap;           // X = B, Y = A (otherwise X = A, Y = B)
            public int pat;             // kernel pattern index, see MultidimensionalArray_CodeGenMultiplySimd.cs
            public int gx, gy;          // strides of X, Y along the vector axis
            public int tr, xr, yr;      // strides along the row axis (tr: in the staging buffer, if staged)
            public bool stage;          // T block staged in a contiguous buffer (row stride lenV)
            public int tvS, trS;        // strides of T along vector and row axis, if staged
            public int NS, K0, sx0, sy0, K1, sx1, sy1;
            public int nOuter;
            public fixed int oLen[GETT_MAXD];
            public fixed int oT[GETT_MAXD];
            public fixed int oX[GETT_MAXD];
            public fixed int oY[GETT_MAXD];
        }

        /// <summary>
        /// true if the entries of T addressed by the running loops are pairwise distinct
        /// (otherwise, the reference kernels accumulate in a traversal-dependent way)
        /// </summary>
        unsafe static bool GettTNonOverlapping(int DT, int* len, int* ct) {
            for(int d = 0; d < DT; d++) {
                if(len[d] <= 1) continue;
                if(ct[d] <= 0) return false;
                for(int e = d + 1; e < DT; e++) {
                    if(len[e] <= 1) continue;
                    if(!((long)ct[d] >= (long)ct[e] * len[e] || (long)ct[e] >= (long)ct[d] * len[d])) return false;
                }
            }
            return true;
        }

        /// <summary>
        /// Classifies a call; false if the blocked SIMD path is not applicable.
        /// </summary>
        unsafe static bool GettPrepare(out GettPlan p, int DT, int NS, int* len, int* ct, int* ca, int* cb, int* lenSum, int* sa, int* sb) {
            p = default;
            if(!Avx2.IsSupported || DT > GETT_MAXD || NS > 2)
                return false;
            for(int s = 0; s < NS; s++)
                if(lenSum[s] <= 0) return false; // the reference kernels leave T untouched for empty sums
            int v = -1;
            for(int d = 0; d < DT; d++) {
                if(len[d] <= 0) return false;
                if(len[d] > 1 && ct[d] == 1 && v < 0) v = d;
            }
            bool stage = false;
            if(v < 0 || (s_GettStageShortVector && len[v] <= 3)) {
                // staged vector axis: longest loop along which an operand varies, preferably with unit stride
                int vs = -1, bestS = -1;
                for(int d = 0; d < DT; d++) {
                    if(len[d] < 4 || (ca[d] == 0 && cb[d] == 0)) continue;
                    int score = len[d] + ((ca[d] == 1 || cb[d] == 1) ? (1 << 20) : 0);
                    if(score > bestS) { bestS = score; vs = d; }
                }
                if(vs >= 0 && len[vs] <= GETT_STAGE_MAX) { v = vs; stage = ct[vs] != 1; }
            }
            if(v < 0) return false;
            if(ca[v] == 0 && cb[v] == 0) return false;

            // X: operand which varies along v (preferably with unit stride), Y: the other one
            bool swap;
            if(ca[v] == 0) swap = true;
            else if(cb[v] == 0) swap = false;
            else swap = ca[v] != 1 && cb[v] == 1;
            int* cx = swap ? cb : ca;
            int* cy = swap ? ca : cb;
            int* sx = swap ? sb : sa;
            int* sy = swap ? sa : sb;
            char XM = cx[v] == 1 ? 'U' : 'G';
            char YM = cy[v] == 0 ? 'B' : cy[v] == 1 ? 'U' : 'G';

            // row axis: prefer an axis along which X is constant (outer product: re-use of the X loads)
            int r = -1, best = -1;
            for(int d = 0; d < DT; d++) {
                if(d == v || len[d] <= 1) continue;
                if(stage && (long)len[d] * len[v] > GETT_STAGE_MAX) continue;
                int score = len[d];
                if(YM == 'B' && cx[d] == 0 && cy[d] != 0) score += 1 << 20;
                if(score > best) { best = score; r = d; }
            }
            bool reuse = YM == 'B' && (r < 0 || cx[r] == 0);

            int pat;
            if(YM == 'B') pat = (XM == 'U' ? 0 : 2) + (reuse ? 0 : 1);
            else if(XM == 'U') pat = YM == 'U' ? 4 : 5;
            else pat = 6; // XM = YM = 'G' (if Y had unit stride, it would have been chosen as X)

            p.lenV = len[v]; p.swap = swap; p.pat = pat;
            p.gx = cx[v]; p.gy = cy[v];
            if(r >= 0) { p.lenR = len[r]; p.tr = ct[r]; p.xr = cx[r]; p.yr = cy[r]; } else { p.lenR = 1; }
            if(stage) {
                p.stage = true; p.tvS = ct[v]; p.trS = p.tr; p.tr = p.lenV;
            }
            p.NS = NS;
            if(NS >= 1) { p.K0 = lenSum[0]; p.sx0 = sx[0]; p.sy0 = sy[0]; }
            if(NS >= 2) { p.K1 = lenSum[1]; p.sx1 = sx[1]; p.sy1 = sy[1]; }
            int n = 0;
            for(int d = 0; d < DT; d++) {
                if(d == v || d == r || len[d] <= 1) continue;
                p.oLen[n] = len[d]; p.oT[n] = ct[d]; p.oX[n] = cx[d]; p.oY[n] = cy[d]; n++;
            }
            p.nOuter = n;
            return true;
        }

        /// <summary>
        /// Selection rule, measured against the generated kernels on the census shapes (pcmit36,
        /// i7-6700): cases in which the blocked SIMD path was slower.
        /// </summary>
        unsafe static bool GettProfitable(ref GettPlan p, int nBatch) {
            long K = (p.NS > 0 ? p.K0 : 1) * (long)(p.NS > 1 ? p.K1 : 1);
            if(p.lenV <= 3 && p.NS > 0 && K <= 4) return false;   // half-empty vectors vs. unrolled scalar reference kernels
            if(p.pat == 3 && K <= 2) return false;                // gathered X without re-use and very short reduction
            long work = (long)p.lenV * p.lenR * K * nBatch;
            for(int i = 0; i < p.nOuter; i++) work *= p.oLen[i];
            if(work < 64) return false;                           // tiny: set-up overhead dominates

            // work per micro-kernel call (cf. GettBlock): small blocks are dominated by the call overhead,
            // gathered operands need more work per call to pay off
            int nvTot = (p.lenV + 3) >> 2, nColBlocks = 0;
            for(int cv = 0; cv < nvTot; nColBlocks++) {
                int nv = nvTot - cv;
                cv += nv > 3 ? (nv == 4 ? 2 : 3) : nv;
            }
            int callsPerBlock = (p.lenR >= 4 ? 1 : 0) + ((p.lenR & 3) != 0 ? 1 : 0);
            long workPerCall = (long)p.lenV * p.lenR * K / (nColBlocks * callsPerBlock);
            if(workPerCall < 25) return false;
            if((p.pat == 2 || p.pat == 3 || p.pat == 6) && workPerCall < 128) return false;
            return true;
        }

        static readonly Vector256<double>[] s_GettMasks = {
            Vector256.Create(-1L, 0, 0, 0).AsDouble(),
            Vector256.Create(-1L, -1L, 0, 0).AsDouble(),
            Vector256.Create(-1L, -1L, -1L, 0).AsDouble(),
            Vector256.Create(-1L, -1L, -1L, -1L).AsDouble(),
        };

        /// <summary> executes a prepared plan for one origin of T, A, B </summary>
        unsafe static void GettExecute(ref GettPlan p, double* t, double* a, double* b, double alpha, double beta) {
            double* x = p.swap ? b : a;
            double* y = p.swap ? a : b;
            double* buf = stackalloc double[p.stage ? p.lenV * p.lenR : 0];
            int nO = p.nOuter;
            if(nO == 0) {
                GettBlockStaged(ref p, t, x, y, alpha, beta, buf);
                return;
            }
            int* idx = stackalloc int[GETT_MAXD];
            for(int i = 0; i < nO; i++) idx[i] = 0;
            fixed(int* oLen = p.oLen, oT = p.oT, oX = p.oX, oY = p.oY) {
                while(true) {
                    GettBlockStaged(ref p, t, x, y, alpha, beta, buf);
                    // odometer over the outer loops, innermost = last
                    int j = nO - 1;
                    while(true) {
                        idx[j]++;
                        t += oT[j]; x += oX[j]; y += oY[j];
                        if(idx[j] < oLen[j]) break;
                        t -= oT[j] * oLen[j]; x -= oX[j] * oLen[j]; y -= oY[j] * oLen[j];
                        idx[j] = 0;
                        j--;
                        if(j < 0) return;
                    }
                }
            }
        }

        unsafe static void GettBlockStaged(ref GettPlan p, double* t, double* x, double* y, double alpha, double beta, double* buf) {
            if(!p.stage) {
                GettBlock(ref p, t, x, y, alpha, beta);
                return;
            }
            int lenV = p.lenV, lenR = p.lenR, tvS = p.tvS, trS = p.trS;
            for(int i = 0; i < lenR; i++)
                for(int j = 0; j < lenV; j++)
                    buf[i * lenV + j] = t[i * trS + j * tvS];
            GettBlock(ref p, buf, x, y, alpha, beta);
            for(int i = 0; i < lenR; i++)
                for(int j = 0; j < lenV; j++)
                    t[i * trS + j * tvS] = buf[i * lenV + j];
        }

        unsafe static void GettBlock(ref GettPlan p, double* t, double* x, double* y, double alpha, double beta) {
            int lenV = p.lenV, lenR = p.lenR;
            int nvTot = (lenV + 3) >> 2;
            int lastLanes = lenV - 4 * (nvTot - 1);
            int gx = p.gx, gy = p.gy;
            int baseIdx = p.pat * 3 + p.NS;
            for(int cv = 0; cv < nvTot;) {
                // column blocks of up to 3 vectors (12 doubles); 4 remaining vectors as 2 + 2
                int nv = nvTot - cv;
                if(nv > 3) nv = (nv == 4) ? 2 : 3;
                var mask = (cv + nv == nvTot) ? s_GettMasks[lastLanes - 1] : s_GettMasks[3];
                int c0 = 4 * cv;
                double* tc = t + c0, xc = x + c0 * gx, yc = y + c0 * gy;
                int nrb = lenR >> 2, r0 = nrb << 2;
                if(nrb > 0)
                    s_GettKernels[((3 * 3 + (nv - 1)) * GETT_NPAT) * 3 + baseIdx](tc, xc, yc, p.tr, p.xr, p.yr, gx, gy,
                        p.K0, p.sx0, p.sy0, p.K1, p.sx1, p.sy1, alpha, beta, mask, nrb);
                int rem = lenR - r0;
                if(rem > 0)
                    s_GettKernels[(((rem - 1) * 3 + (nv - 1)) * GETT_NPAT) * 3 + baseIdx](tc + r0 * p.tr, xc + r0 * p.xr, yc + r0 * p.yr, p.tr, p.xr, p.yr, gx, gy,
                        p.K0, p.sx0, p.sy0, p.K1, p.sx1, p.sy1, alpha, beta, mask, 1);
                cv += nv;
            }
        }

        /// <summary>
        /// true if <see cref="TryMultiplyGett"/> would take a call with this loop description
        /// (for transformed calls: inner loops, with <paramref name="nBatch"/> = length of the transformed loop;
        /// the caller must check <see cref="GettTNonOverlapping"/> for all loops)
        /// </summary>
        unsafe static bool GettWouldRun(int DT, int NS, int* len, int* ct, int* ca, int* cb, int* lenSum, int* sa, int* sb, int nBatch) {
#if MULTIPLY_FASTPATH_DIAGNOSTICS
            if(s_FastPathOff || s_GettOff)
                return false;
#endif
            return GettPrepare(out GettPlan p, DT, NS, len, ct, ca, cb, lenSum, sa, sb)
                && GettProfitable(ref p, nBatch)
                && GettTNonOverlapping(DT, len, ct);
        }

        /// <summary>
        /// blocked SIMD path for Multiply without index transformation;
        /// false: not applicable or not profitable, T unchanged
        /// </summary>
        unsafe static bool TryMultiplyGett(int DT, int NS, double* t, double* a, double* b, int* len, int* ct, int* ca, int* cb,
            int* lenSum, int* sa, int* sb, double alpha, double beta, bool directAllowed) {
            if(!directAllowed)
                return false;
#if MULTIPLY_FASTPATH_DIAGNOSTICS
            if(s_FastPathOff || s_GettOff)
                return false;
#endif
            if(!GettRun(DT, NS, t, a, b, len, ct, ca, cb, lenSum, sa, sb, alpha, beta, true))
                return false;
            return FastPathSelected("Gett");
        }

        /// <summary>
        /// core of <see cref="TryMultiplyGett"/>; <paramref name="profitableOnly"/> = false only for testing
        /// </summary>
        unsafe static bool GettRun(int DT, int NS, double* t, double* a, double* b, int* len, int* ct, int* ca, int* cb,
            int* lenSum, int* sa, int* sb, double alpha, double beta, bool profitableOnly) {
            if(!GettPrepare(out GettPlan p, DT, NS, len, ct, ca, cb, lenSum, sa, sb))
                return false;
            if((profitableOnly && !GettProfitable(ref p, 1)) || !GettTNonOverlapping(DT, len, ct))
                return false;
            GettExecute(ref p, t, a, b, alpha, beta);
            return true;
        }

        /// <summary>
        /// blocked SIMD path for Multiply with index transformation (the transformed loop is loop 0,
        /// as arranged by the Multiply driver); same semantics as MultiplyWTrafo_Dispatch, i.e.
        /// entries with negative mapped indices are skipped; false: not applicable or not profitable, T unchanged
        /// </summary>
        unsafe static bool TryMultiplyGettWTrafo(int DT, int NS, double* t, double* a, double* b, int* len, int* ct, int* ca, int* cb,
            int* lenSum, int* sa, int* sb, double alpha, double beta,
            int* trfT, int* trfA, int* trfB, int trfT0sw, int trfA0sw, int trfB0sw,
            int preT, int cycT, int postT, int preA, int cycA, int postA, int preB, int cycB, int postB, bool directAllowed) {
            if(!directAllowed)
                return false;
#if MULTIPLY_FASTPATH_DIAGNOSTICS
            if(s_FastPathOff || s_GettOff)
                return false;
#endif
            if(!GettRunWTrafo(DT, NS, t, a, b, len, ct, ca, cb, lenSum, sa, sb, alpha, beta,
                trfT, trfA, trfB, trfT0sw, trfA0sw, trfB0sw, preT, cycT, postT, preA, cycA, postA, preB, cycB, postB, true))
                return false;
            return FastPathSelected("GettWTrafo");
        }

        /// <summary>
        /// core of <see cref="TryMultiplyGettWTrafo"/>; <paramref name="profitableOnly"/> = false only for testing
        /// </summary>
        unsafe static bool GettRunWTrafo(int DT, int NS, double* t, double* a, double* b, int* len, int* ct, int* ca, int* cb,
            int* lenSum, int* sa, int* sb, double alpha, double beta,
            int* trfT, int* trfA, int* trfB, int trfT0sw, int trfA0sw, int trfB0sw,
            int preT, int cycT, int postT, int preA, int cycA, int postA, int preB, int cycB, int postB, bool profitableOnly) {
            if(DT < 2 || len[0] < 1)
                return false;
            if(!GettPrepare(out GettPlan p, DT - 1, NS, len + 1, ct + 1, ca + 1, cb + 1, lenSum, sa, sb))
                return false;
            if((profitableOnly && !GettProfitable(ref p, len[0])) || !GettTNonOverlapping(DT, len, ct))
                return false;
            int I0 = len[0];
            for(int i0 = 0; i0 < I0; i0++) {
                int ti = (trfT[i0 * cycT + preT] + postT) * trfT0sw;
                int ai = (trfA[i0 * cycA + preA] + postA) * trfA0sw;
                int bi = (trfB[i0 * cycB + preB] + postB) * trfB0sw;
                if(ti < 0 || ai < 0 || bi < 0) continue;
                GettExecute(ref p,
                    t + ct[0] * (i0 * (1 - trfT0sw) + ti),
                    a + ca[0] * (i0 * (1 - trfA0sw) + ai),
                    b + cb[0] * (i0 * (1 - trfB0sw) + bi), alpha, beta);
            }
            return true;
        }
    }
